# Arthematic operators
# + Addition  - Subtraction  * Multiplication  /  Division  %  Remainder  ** Exponentiation

# Arthematic built in mathematical functions
# round() : A built in function to rounding off a decimal number

x = 3.14
y = -2
z = 8

result = round(x)
print(result)

# abs() : It is a function known as absolute value function which gives absolute value of the given number simply said no negative number allowed
result1 = abs(y)
print(result1)

# pow() : It is a function that finds the power of given base with the given indices
result2 = pow(y, 4)
print(result2)

# max() : It is the function which gives maximum number among given numbers
# min() : It is the function which gives minimum number among given numbers
result3 = max(x, y, z)
print(result3)

result4 = min(x, y, z)
print(result4)
# Show .format() to display

# print("The {} {} are priced {}.".format(Quantity, Item, Price))
print("{:<15} {:^10} {:>15}".format("Item", "Quantity", "Price"))
print("{:<15} {:^10} {:>15}".format("Sugar", "2Kg", 120))
print("{:<15} {:^10} {:>15}".format("Tea Leaves", "200g", 70))
print("{:<15} {:^10} {:>15}".format("Milk","1L", 77))
print("{:<15} {:^10} {:>15}".format("Bread","1", 40))